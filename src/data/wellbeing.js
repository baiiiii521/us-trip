// 现在该看哪一条：出发前 4 天起显示 pre，12/17 显示福州那晚，行程头四天各一条，12/31 显示回国
export function jetlagFor(phase, dayId) {
  if (phase && phase.phase === 'before') {
    if (phase.days === 1) return JETLAG[1217];
    if (phase.days <= 4) return JETLAG.pre;
    return null;
  }
  if (dayId === '1231') return JETLAG.back;
  return JETLAG[dayId] || null;
}

