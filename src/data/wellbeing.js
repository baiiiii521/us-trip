// 每天的节奏（days.js 里每天的 pace.lv）
export const PACE = { 1: '轻松', 2: '适中', 3: '紧凑' };

export function paceText(pace) {
  if (!pace) return '';
  return `步行约 ${pace.km} 公里 · ${PACE[pace.lv] || ''}`;
}

